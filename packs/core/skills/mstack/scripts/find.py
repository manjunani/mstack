#!/usr/bin/env python3
"""Look up mstack skills in the generated skill map.

  search WORDS...   the skills that best match a task, with their pack and install line
  list [--pack P]   every skill, or one pack's skills
  packs             every pack and what it covers

The map is references/skills.json, generated by the mstack repository. This script only reads it.
Exit codes: 0 = answered (including "no skill fits"), 2 = blocked: the map is missing.
"""
import argparse
import json
import pathlib
import re
import sys

MAP = pathlib.Path(__file__).resolve().parent.parent / "references" / "skills.json"
STOP = set("a an the and or of to in on for with is are be it this that my our i we you how do does can want need "
           "use when not skill skills there one any some please help me".split())


def words(text):
    return [w for w in re.findall(r"[a-z0-9]+", text.lower()) if w not in STOP and len(w) > 1]


def stem(word):
    for suffix in ("ing", "ed", "es", "s"):
        if len(word) > len(suffix) + 2 and word.endswith(suffix):
            return word[: -len(suffix)]
    return word


def score(skill, query):
    name = {stem(w) for w in words(skill["name"].replace("-", " "))}
    use = {stem(w) for w in words(skill["description"].split("Not for")[0])}
    return sum(3 if q in name else 1 if q in use else 0 for q in {stem(w) for w in query})


def show(skill, packs):
    pack = packs.get(skill["pack"], {})
    tests = skill["tests"] if isinstance(skill["tests"], str) else ", ".join(f"{k} {v}" for k, v in skill["tests"].items())
    print(f"{skill['name']}  ({skill['pack']})")
    print(f"    {skill['description']}")
    print(f"    needs: {', '.join(skill['needs']) or 'nothing extra'}   tests: {tests}")
    print(f"    install the pack: {pack.get('install', '?')}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--map", type=pathlib.Path, default=MAP, help="path to skills.json (default: the copy shipped with this skill)")
    sub = parser.add_subparsers(dest="action", required=True)
    sub.add_parser("search", help="find skills for a task").add_argument("words", nargs="+")
    sub.add_parser("list", help="list skills").add_argument("--pack")
    sub.add_parser("packs", help="list packs")
    args = parser.parse_args()
    if not args.map.exists():
        print(f"blocked: no skill map at {args.map}")
        return 2
    data = json.loads(args.map.read_text(encoding="utf-8"))
    packs = {p["name"]: p for p in data["packs"]}

    if args.action == "packs":
        for pack in data["packs"]:
            print(f"{pack['name']}  ({len(pack['skills'])} skills)  {pack['description']}")
            print(f"    {pack['install']}")
        return 0
    if args.action == "list":
        wanted = args.pack and (args.pack if args.pack.startswith("mstack-") else f"mstack-{args.pack}")
        for skill in data["skills"]:
            if not wanted or skill["pack"] == wanted:
                print(f"{skill['name']:18} {skill['pack']:16} {skill['description'].split('. ')[0]}.")
        return 0
    query = words(" ".join(args.words))
    ranked = sorted(((score(s, query), s) for s in data["skills"]), key=lambda pair: -pair[0])
    hits = [s for points, s in ranked if points >= 2][:3]
    if not hits:
        print(f"no skill fits: nothing in mstack {data['version']} matches \"{' '.join(args.words)}\".")
        print("That is a valid answer. Do the task directly, or try other words.")
        return 0
    for skill in hits:
        show(skill, packs)
    print(f"\n{len(hits)} of {len(data['skills'])} skills shown. A match on words is a suggestion: read the description before choosing.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
